void put_le16(uint8_t *data, uint16_t value)
{
    data[0] = uint8_t(value);
    data[1] = uint8_t(value >> 8);
}

// Chipsemi 3536 burn helper. The caller owns the controller in direct mode
// until it resets or power-cycles the touch controller after programming.
class chsc6x_burn {
public:
    chsc6x_burn(chsc6x_platform &bus, const chsc6x_update_observer &observer)
        : bus_(bus), observer_(observer) {}

    bool start();
    chsc6x_compare_status compare_flash(chsc6x_update_part part, const uint8_t *target, uint16_t len,
                                        int32_t &firstDifference);
    bool write_cfg(const uint8_t *data);
    bool write_boot(const uint8_t *data, uint16_t len);

private:
    enum class command_result { ok, retry, stop };

    bool read_flash(uint16_t addr, uint8_t *data, uint16_t len);
    bool write_ram(uint16_t addr, const uint8_t *data, uint16_t len);
    bool matches_ram(uint16_t addr, const uint8_t *data, uint16_t len);
    bool load_checked(uint16_t addr, const uint8_t *data, uint16_t len);
    command_result send_command(uint8_t id, uint16_t addr, uint16_t len,
                                uint32_t checksum, uint8_t (&response)[8]);
    chsc6x_compare_status verify_flash(uint16_t addr, const uint8_t *expected, uint16_t len,
                                      bool finalBootReadback = false);
    bool write_block(uint16_t addr, const uint8_t *data, uint16_t len);
    bool program(chsc6x_update_part part, const uint8_t *data, uint16_t len);
    void progress(chsc6x_update_part part, chsc6x_update_phase phase, uint32_t done, uint32_t total) const
    {
        if (observer_.progress) {
            observer_.progress(part, phase, done, total);
        }
    }

    chsc6x_platform &bus_;
    const chsc6x_update_observer &observer_;
};

bool chsc6x_burn::write_ram(uint16_t addr, const uint8_t *data, uint16_t len)
{
    // A 32-byte Wire transmission includes the two register-address bytes.
    while (len > 0) {
        const uint16_t count = len > 30 ? 30 : len;
        if (bus_.chsc6x_write_bytes_u16addr(bus_._i2c_addr, addr, data, count) != OS_OK) {
            return false;
        }
        addr += count;
        data += count;
        len -= count;
    }
    return true;
}

bool chsc6x_burn::matches_ram(uint16_t addr, const uint8_t *data, uint16_t len)
{
    uint8_t actual[32];
    while (len > 0) {
        const uint16_t count = len > sizeof(actual) ? sizeof(actual) : len;
        if (bus_.chsc6x_read_bytes_u16addr(bus_._i2c_addr, addr, actual, count) != OS_OK ||
            memcmp(actual, data, count) != 0) {
            return false;
        }
        addr += count;
        data += count;
        len -= count;
    }
    return true;
}

bool chsc6x_burn::load_checked(uint16_t addr, const uint8_t *data, uint16_t len)
{
    while (len > 0) {
        const uint16_t count = len > 128 ? 128 : len;
        uint8_t attempt = 0;
        while (!write_ram(addr, data, count) || !matches_ram(addr, data, count)) {
            if (++attempt == attempts) {
                return false;
            }
        }
        addr += count;
        data += count;
        len -= count;
    }
    return true;
}

bool chsc6x_burn::start()
{
    const uint8_t stop = 0x05;
    const uint8_t disable_irq = 0;
    const uint8_t run = 0x88;
    if (!load_checked(0x0602, &stop, 1) ||
        !load_checked(0x0643, &disable_irq, 1) ||
        !load_checked(0x8000, fw_fcode_burn, sizeof(fw_fcode_burn))) {
        return false;
    }
    for (uint8_t attempt = 0; attempt < attempts; ++attempt) {
        if (write_ram(0x0602, &run, 1)) {
            bus_.chsc6x_msleep(30);
            return true;
        }
    }
    return false;
}

chsc6x_burn::command_result chsc6x_burn::send_command(
    uint8_t id, uint16_t addr, uint16_t len, uint32_t checksum, uint8_t (&response)[8])
{
    const uint8_t clear = 0;
    const uint8_t trigger = 0x35;
    uint8_t packet[16] = {};
    packet[0] = id;
    packet[1] = uint8_t(~id);
    put_le16(packet + 2, addr);
    put_le16(packet + 4, len);
    put_le16(packet + 6, uint16_t(checksum));
    packet[8] = id == write_command ? 0x11 : 0x03;
    packet[9] = trigger;
    put_le16(packet + 10, uint16_t(0 - sum16(packet, 10)));
    put_le16(packet + 12, uint16_t(checksum >> 16));
    packet[9] = 0x30;
    if (!write_ram(response_address, &clear, 1) ||
        !write_ram(command_address, packet, sizeof(packet))) {
        return command_result::retry;
    }

    // A failed transfer of the trigger byte can still have reached the chip.
    // Wait for a valid reply before restaging its shared command/data buffer.
    write_ram(command_address + 9, &trigger, 1);
    for (uint8_t poll = 0; poll < 100; ++poll) {
        bus_.chsc6x_msleep(20);
        if (bus_.chsc6x_read_bytes_u16addr(bus_._i2c_addr, response_address,
                                          response, sizeof(response)) != OS_OK ||
            response[0] != id || sum16(response, sizeof(response)) != 0) {
            continue;
        }
        if (response[1] == 0) {
            return command_result::ok;
        }
        if (response[1] == 0x09 && le16(response + 2) == 0x05) {
            return command_result::stop;
        }
        return command_result::retry;
    }
    return command_result::stop;
}

bool chsc6x_burn::read_flash(uint16_t addr, uint8_t *data, uint16_t len)
{
    if (!data || len == 0 || len > block_size || uint32_t(addr) + len > 0x10000UL) {
        return false;
    }
    for (uint8_t attempt = 0; attempt < attempts; ++attempt) {
        uint8_t response[8];
        const auto result = send_command(read_command, addr, len, 0, response);
        if (result == command_result::stop) {
            return false;
        }
        if (result != command_result::ok) {
            continue;
        }

        uint16_t offset = 0;
        while (offset < len) {
            const uint16_t remaining = len - offset;
            const uint16_t count = remaining < MAX_IIC_RD_LEN ? remaining : MAX_IIC_RD_LEN;
            if (bus_.chsc6x_read_bytes_u16addr(bus_._i2c_addr, data_address + offset,
                                               data + offset, count) != OS_OK) {
                break;
            }
            offset += count;
        }
        // The helper checksum describes the bytes in flash, including any genuine mismatch.
        if (offset == len && checksum_ex(data, len) == le32(response + 2)) {
            return true;
        }
    }
    return false;
}

chsc6x_compare_status chsc6x_burn::verify_flash(uint16_t addr, const uint8_t *expected, uint16_t len,
                                              bool finalBootReadback)
{
    uint8_t actual[block_size];
    auto result = chsc6x_compare_status::identical;
    uint16_t offset = 0;
    while (offset < len) {
        const uint16_t remaining = len - offset;
        const uint16_t count = remaining < block_size ? remaining : block_size;
        if (!read_flash(addr + offset, actual, count)) {
            return chsc6x_compare_status::read_error;
        }
        if (memcmp(actual, expected + offset, count) != 0) {
            result = chsc6x_compare_status::different;
        }
        offset += count;
        if (finalBootReadback && result == chsc6x_compare_status::identical) {
            progress(chsc6x_update_part::boot, chsc6x_update_phase::verify, uint32_t(len) + offset, 2UL * len);
        }
    }
    return result;
}

chsc6x_compare_status chsc6x_burn::compare_flash(chsc6x_update_part part, const uint8_t *target, uint16_t len,
                                                int32_t &firstDifference)
{
    const uint16_t addr = part == chsc6x_update_part::cfg ? cfg_address : 0;
    firstDifference = -1;
    if (!target || len == 0 || uint32_t(addr) + len > 0x10000UL) {
        return chsc6x_compare_status::read_error;
    }
    uint8_t actual[block_size];
    int32_t first = -1;
    uint16_t offset = 0;
    progress(part, chsc6x_update_phase::compare, 0, len);
    while (offset < len) {
        const uint16_t remaining = len - offset;
        const uint16_t count = remaining < block_size ? remaining : block_size;
        const uint16_t blockAddress = addr + offset;
        if (!read_flash(blockAddress, actual, count)) {
            return chsc6x_compare_status::read_error;
        }
        uint16_t i = 0;
        while (i < count && actual[i] == target[offset + i]) {
            ++i;
        }
        if (i < count) {
            // Confirm the whole first snapshot, including any bytes that matched the package.
            const auto confirmation = verify_flash(blockAddress, actual, count);
            if (confirmation == chsc6x_compare_status::read_error) {
                return confirmation;
            }
            if (confirmation == chsc6x_compare_status::different) {
                return chsc6x_compare_status::inconsistent_reads;
            }
            if (first < 0) {
                first = offset + i;
            }
        }
        offset += count;
        progress(part, chsc6x_update_phase::compare, offset, len);
    }
    // Publish a difference only after the entire requested region was read reliably.
    firstDifference = first;
    return first < 0 ? chsc6x_compare_status::identical : chsc6x_compare_status::different;
}

bool chsc6x_burn::write_block(uint16_t addr, const uint8_t *data, uint16_t len)
{
    const uint32_t checksum = checksum_ex(data, len);
    for (uint8_t attempt = 0; attempt < attempts; ++attempt) {
        if (!write_ram(data_address, data, len)) {
            continue;
        }
        uint8_t response[8];
        const auto result = send_command(write_command, addr, len, checksum, response);
        if (result == command_result::ok) {
            return true;
        }
        if (result == command_result::stop) {
            return false;
        }
    }
    return false;
}

bool chsc6x_burn::program(chsc6x_update_part part, const uint8_t *data, uint16_t len)
{
    const bool boot = part == chsc6x_update_part::boot;
    const uint16_t base = boot ? 0 : cfg_address;
    const uint32_t writeTotal = boot ? uint32_t(len) + 1 : len;
    const uint32_t verifyTotal = boot ? 2UL * len : len;
    uint16_t offset = 0;
    progress(part, chsc6x_update_phase::write, 0, writeTotal);
    while (offset < len) {
        const uint16_t remaining = len - offset;
        const uint16_t count = remaining < block_size ? remaining : block_size;
        if (!write_block(base + offset, data + offset, count)) {
            return false;
        }
        progress(part, chsc6x_update_phase::write, offset + count, writeTotal);
        if (offset == 0) {
            progress(part, chsc6x_update_phase::verify, 0, verifyTotal);
        }
        if (verify_flash(base + offset, data + offset, count) != chsc6x_compare_status::identical) {
            return false;
        }
        offset += count;
        progress(part, chsc6x_update_phase::verify, offset, verifyTotal);
    }
    return true;
}

bool chsc6x_burn::write_cfg(const uint8_t *data)
{
    return data && program(chsc6x_update_part::cfg, data, sizeof(chsc6x_cfg::bytes));
}

bool chsc6x_burn::write_boot(const uint8_t *data, uint16_t len)
{
    if (!data || len <= 8 || len > cfg_address || data[8] != 0x4B) {
        return false;
    }
    // The vendor writes the complete image, then programs byte 8 again.
    if (!program(chsc6x_update_part::boot, data, len) || !write_block(8, data + 8, 1)) {
        return false;
    }
    const uint32_t writeTotal = uint32_t(len) + 1;
    progress(chsc6x_update_part::boot, chsc6x_update_phase::write, writeTotal, writeTotal);
    return verify_flash(0, data, len, true) == chsc6x_compare_status::identical;
}

bool read_probe_register(chsc6x_platform &bus, uint16_t address, uint8_t *data, uint16_t length)
{
    for (uint8_t attempt = 0; attempt < attempts; ++attempt) {
        if (bus.chsc6x_read_bytes_u16addr(bus._i2c_addr, address, data, length) == OS_OK) {
            return true;
        }
    }
    return false;
}

bool select_parts(uint32_t identity, const UpdateImage &image, chsc6x_update_result &report)
{
    const bool cfg = identity == image.cfg_identity;
    const bool boot = (identity & bootIdentityMask) == image.boot_match;
    report.cfg.comparison = cfg ? chsc6x_compare_status::not_checked : chsc6x_compare_status::not_applicable;
    report.boot.comparison = boot ? chsc6x_compare_status::not_checked : chsc6x_compare_status::not_applicable;
    return cfg || boot;
}

bool compare_part(chsc6x_burn &burner, chsc6x_update_part component, const uint8_t *data, uint16_t length,
                  chsc6x_part_result &part)
{
    if (part.comparison == chsc6x_compare_status::not_applicable) {
        return true;
    }
    part.comparison = burner.compare_flash(component, data, length, part.first_difference);
    return part.comparison == chsc6x_compare_status::identical ||
           part.comparison == chsc6x_compare_status::different;
}

bool sync_parts(chsc6x_burn &burner, const UpdateImage &image, chsc6x_update_result &report,
                chsc6x_init_result &init)
{
    init.stage = "compare_cfg";
    if (!compare_part(burner, chsc6x_update_part::cfg, image.cfg, sizeof(chsc6x_cfg::bytes), report.cfg)) {
        return false;
    }
    init.stage = "compare_boot";
    if (!compare_part(burner, chsc6x_update_part::boot, image.boot, image.boot_size, report.boot)) {
        return false;
    }

    if (report.cfg.comparison == chsc6x_compare_status::different) {
        init.stage = "cfg_write_verify";
        report.cfg.write_attempted = true;
        init.cfg_written = burner.write_cfg(image.cfg);
        if (!init.cfg_written) {
            return false;
        }
    }
    if (report.boot.comparison == chsc6x_compare_status::different) {
        init.stage = "boot_write_verify";
        report.boot.write_attempted = true;
        init.boot_written = burner.write_boot(image.boot, image.boot_size);
        return init.boot_written;
    }
    return true;
}

